import test from 'node:test';
import assert from 'node:assert/strict';
import {applyAction,createInitialWorld,ensureProfile,migrateWorld} from '../src/shared/temple-rules.js';
import {applySpacePaint} from '../src/shared/space-paint.js';
import {CITY_LOTS,cityWallPoint} from '../src/shared/city-layout.js';
import {TempleNetwork} from '../src/network.js';
import {readFileSync} from 'node:fs';
const account='firebase:temple:stable-uid',other='firebase:temple:other-uid';
const actor=(key,session,position)=>({key,id:session,name:'Artist',color:'#112233',role:'fighter',position,admin:false});
const g={id:'relogin-stroke-1',color:'#ff00aa',size:.5,thickness:.4,normal:[0,0,1],points:[[-2,3,0],[2,3,0]]};
test('2D facade and disc ownership survives session and device replacement; an immediate erase succeeds',()=>{
 let w=createInitialWorld();const lot=CITY_LOTS.find(l=>l.floors>=2),p=cityWallPoint(lot,'front',.5,.8),pos=[p[0],p[1],p[2]+1];
 const first=actor(account,'tablet-session',pos),next=actor(account,'phone-session',pos),stranger=actor(other,'other-session',pos);
 for(const a of [first,stranger])ensureProfile(w,a.key,a.name,a.color,Date.now(),false);
 const s={lotId:lot.id,wall:'front',tool:'brush',color:'#123456',size:.18,points:[[.5,.8]]};
 assert.equal(applyAction(w,first,{action:'paint-building',stroke:s}).paintStroke.owner,account);
 assert.equal(applyAction(w,first,{action:'paint-building',stroke:{...s,tool:'eraser'}}).paintStroke.eraseOwn,true);
 w=migrateWorld(JSON.parse(JSON.stringify(w)));
 assert.equal(applyAction(w,next,{action:'paint-building',stroke:{...s,tool:'eraser',owner:other}}).paintStroke.owner,account);
 assert.ok(applyAction(w,stranger,{action:'paint-building',stroke:{...s,tool:'eraser',owner:account}}).error);
 w.floatingPlatforms=[{id:'test-disc',position:[70,3,0],radius:3}];
 first.position=next.position=stranger.position=[70,3,0];
 const d={...s,lotId:'floating:test-disc',wall:'top',points:[[.5,.5]]};
 assert.equal(applyAction(w,first,{action:'paint-disc',stroke:d}).paintStroke.owner,account);
 assert.equal(applyAction(w,next,{action:'paint-disc',stroke:{...d,tool:'eraser'}}).paintStroke.eraseOwn,true);
 assert.ok(applyAction(w,stranger,{action:'paint-disc',stroke:{...d,tool:'eraser'}}).error);
});
test('3D geometry and surface paint use persistent account keys rather than session IDs',()=>{
 const first=actor(account,'tablet-session',[0,2,0]),next=actor(account,'phone-session',[0,2,0]),stranger=actor(other,'other-session',[0,2,0]);
 let w={profiles:{[account]:{hp:100,spacePaintEnabled:true},[other]:{hp:100,spacePaintEnabled:true}},spacePaint:[],spacePaintSurface:{},revision:0};
 const act=(a,action,data)=>applySpacePaint(w,a,{action,...data});
 assert.equal(act(first,'gm-paint-3d',{stroke:g}).spacePaintStroke.ownerKey,account);
 const s={id:g.id,chart:0,tool:'brush',color:'#112233',size:.2,points:[[.5,.5]]};
 assert.ok(act(first,'paint-space-surface',{stroke:s}).spaceSurfacePainted);
 assert.ok(act(first,'paint-space-surface',{stroke:{...s,tool:'eraser'}}).spaceSurfacePainted);
 w=JSON.parse(JSON.stringify(w));
 assert.ok(act(next,'paint-space-surface',{stroke:{...s,tool:'eraser'}}).spaceSurfacePainted);
 assert.ok(act(stranger,'paint-space-surface',{stroke:{...s,tool:'eraser',owner:account}}).error);
 assert.ok(act(stranger,'gm-erase-3d',{id:g.id}).error);
 assert.equal(act(next,'gm-erase-3d',{id:g.id}).erased3DStroke,g.id);
});
